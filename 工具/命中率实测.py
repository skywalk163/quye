"""极快选块命中率实测（spec §4.5 风险 B）。

在 出/静态/py/极快 布局上跑 retrieve —— 与浏览器 Pyodide 里的目录布局一致，
所以这里的命中率就是用户在 /台 上能感受到的命中率。

用法：先 python 建站.py 产出语言包，再 python 工具/命中率实测.py
退出码：命中率 >= 阈值 返回 0，否则返回 1。
阈值：M3 实测 83%，M4 门禁提到 80%（贴着实测值，上游一退化就红牌）。
"""
import os
import sys
from pathlib import Path

基 = Path(__file__).resolve().parent.parent / "出" / "静态" / "py" / "极快"
if not 基.exists():
    print(f"语言包不存在：{基}\n请先跑 python 建站.py")
    sys.exit(2)
os.environ["JIKUAI_PATH"] = str(基 / "stdlib")
sys.path.insert(0, str(基))

from jikuai.ai.retrieval import retrieve  # noqa: E402

TOP = 5

# 30 条真实需求 → 期望命中的块名关键词（子串匹配，命中 top-5 即算过）
# 关键词按极快块库的真实命名校准（如「求平均」对应块名「均值」、「最大」对应「极值」）。
用例 = [
    ("月薪两万个税多少", "个税"),
    ("帮我算增值税", "增值税"),
    ("等额本息每月还多少", "等额本息"),
    ("算复利终值", "复利"),
    ("一笔钱按折现率折成现值", "贴现"),
    ("年化收益率怎么算", "收益率"),
    ("求一组数的总和", "求和"),
    ("求平均值", "均值"),
    ("找出最大值", "极值"),
    ("找出最小值", "极值"),
    ("算标准差", "标准差"),
    ("算中位数", "中位数"),
    ("数据去重", "去重"),
    ("列表排序", "序"),
    ("过滤掉不满足条件的数据", "过滤"),
    ("统计每个分类出现多少次", "批量统计"),
    ("公历转农历", "农历"),
    ("今天是农历几月几号", "农历"),
    ("计算两个日期相差多少天", "日差"),
    ("判断是不是闰年", "闰年"),
    ("身份证号校验", "身份证"),
    ("手机号格式对不对", "手机"),
    ("字符串去掉首尾空格", "清洗"),
    ("把文本拆成一个个词", "切分"),
    ("金额转成中文大写", "雅写"),
    ("数字保留两位小数", "取整"),
    ("百分比怎么算", "百分"),
    ("把数据按某个字段分组", "分组"),
    ("两个列表合并", "合并"),
    ("生成指定范围的随机数", "随机"),
]


def 主() -> float:
    命中 = 0
    漏 = []
    for 需求, 期望 in 用例:
        try:
            结果 = retrieve(需求, top=TOP)
        except Exception as e:
            漏.append((需求, 期望, f"异常:{type(e).__name__}:{e}"))
            continue
        名单 = [h.name for h in 结果]
        if any(期望 in n for n in 名单):
            命中 += 1
        else:
            漏.append((需求, 期望, 名单))
    总 = len(用例)
    率 = 命中 / 总 if 总 else 0.0
    print(f"命中 {命中}/{总} = {率:.0%}（top-{TOP}）")
    if 漏:
        print("未命中明细（需求 / 期望关键词 / 实际候选）：")
        for 需求, 期望, 名单 in 漏:
            print(f"  {需求} | {期望} | {名单}")
    return 率


THRESHOLD = 0.8  # M4: 从 60% 提到 80%（实测 83% 有余量）

if __name__ == "__main__":
    率 = 主()
    sys.exit(0 if 率 >= THRESHOLD else 1)
